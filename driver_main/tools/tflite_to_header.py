"""Embed a trusted .tflite file and its exact training class order. No dependencies.

This encodes bytes; it does not train, quantize, or guarantee TFLite Micro support.
Run from the project root:
    python tools/tflite_to_header.py model.tflite --labels labels.txt
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def render(data, labels):
    if len(data) < 12 or data[4:8] != b"TFL3":
        raise ValueError("Not a TFLite flatbuffer (missing TFL3 identifier).")
    root = struct.unpack_from("<I", data)[0]
    if root < 8 or root >= len(data) - 3:
        raise ValueError("Invalid flatbuffer root offset.")
    if not 2 <= len(labels) <= 27 or len(set(labels)) != len(labels):
        raise ValueError("Need 2..27 unique labels, including ! and at least one letter.")
    if "!" not in labels or any(len(x) != 1 or x not in "!abcdefghijklmnopqrstuvwxyz" for x in labels):
        raise ValueError("Labels must be ! or lowercase a-z; include ! for no gesture.")
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i+12]) + ","
            for i in range(0, len(data), 12)]
    label_values = ", ".join(json.dumps(x) for x in labels)
    tracks = ", ".join(str(0 if x == "!" else ord(x) - ord("a") + 1) for x in labels)
    return "\n".join([
        "#pragma once", "#include <cstddef>", "#include <cstdint>",
        "// Generated by tools/tflite_to_header.py. Do not edit manually.",
        f"// Model SHA256: {hashlib.sha256(data).hexdigest()}",
        "#define GLOVE_HAS_MODEL 1",
        "alignas(16) inline constexpr unsigned char g_model_data[] = {",
        *rows, "};", "inline constexpr std::size_t g_model_data_len = sizeof(g_model_data);",
        f"inline constexpr int kClassCount = {len(labels)};",
        f"inline constexpr const char *kLabels[] = {{{label_values}}};",
        f"inline constexpr uint16_t kTracks[] = {{{tracks}}};", ""
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path)
    parser.add_argument("--labels", required=True, type=Path, help="One label per line in EXACT output-index order")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "main/model/model_data.h")
    args = parser.parse_args()
    try:
        data = args.model.read_bytes()
        labels = [x.strip() for x in args.labels.read_text(encoding="utf-8-sig").splitlines() if x.strip()]
        header = render(data, labels)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary = args.output.with_suffix(args.output.suffix + ".tmp")
        temporary.write_text(header, encoding="utf-8")
        temporary.replace(args.output)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Error: {error}\n")
    print(f"Wrote {args.output}: {len(data)} model bytes, {len(labels)} classes")
    print("Basic file check only. Verify shapes, preprocessing and operators; then rebuild and flash.")


if __name__ == "__main__":
    main()
